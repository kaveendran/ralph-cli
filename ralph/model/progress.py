"""The old markdown progress file (read for `ralph migrate`) and the new
generated progress view.

In the old format the agent kept one big file: a checklist of units
(`- [x] U033 …`, sometimes with a bold ID), milestone headings, rollups, and
per-unit detail blocks (`### U033 — …`). The new harness keeps state in
`units/*.json` and only *generates* a progress view from it.
"""

import re
from dataclasses import dataclass, field
from pathlib import Path

from ralph.model.unit import Status, Unit

LEGACY_UNIT_LINE = re.compile(r"^- \[(?P<mark>[ x~!])\] (?:\*\*)?(?P<id>U\d+)\b\**\s*(?P<rest>.*)$")
DETAIL_HEADING = re.compile(r"^(#{2,4})\s+(?P<id>U\d+)\b")
MARKS = {"x": Status.DONE, "~": Status.IN_PROGRESS, " ": Status.TODO, "!": Status.BLOCKED}
SYMBOLS = {Status.DONE: "x", Status.IN_PROGRESS: "~", Status.TODO: " ", Status.BLOCKED: "!"}


@dataclass
class LegacyEntry:
    id: str
    status: Status
    text: str                    # the rest of the checklist line


@dataclass
class LegacyProgress:
    entries: dict[str, LegacyEntry] = field(default_factory=dict)
    details: dict[str, str] = field(default_factory=dict)      # unit ID → detail block


def parse_legacy_progress_text(text: str) -> LegacyProgress:
    progress = LegacyProgress()
    lines = text.splitlines()
    in_comment = False
    for line in lines:
        if "<!--" in line:
            in_comment = "-->" not in line
            continue
        if in_comment:
            in_comment = "-->" not in line
            continue
        match = LEGACY_UNIT_LINE.match(line)
        if match and match.group("id") not in progress.entries:
            progress.entries[match.group("id")] = LegacyEntry(
                match.group("id"), MARKS[match.group("mark")], match.group("rest").strip())

    # Detail blocks: from "### U033 — …" to the next heading of the same or a higher level.
    for index, line in enumerate(lines):
        match = DETAIL_HEADING.match(line)
        if not match:
            continue
        level = len(match.group(1))
        end = len(lines)
        for later in range(index + 1, len(lines)):
            heading = re.match(r"^(#{1,6})\s", lines[later])
            if heading and len(heading.group(1)) <= level:
                end = later
                break
        progress.details.setdefault(match.group("id"), "\n".join(lines[index:end]).strip() + "\n")
    return progress


def parse_legacy_progress(path: Path) -> LegacyProgress:
    if not path.exists():
        return LegacyProgress()
    return parse_legacy_progress_text(path.read_text(encoding="utf-8"))


def render_progress_view(cr: str, units: list[Unit]) -> str:
    """The generated PROGRESS.md: a read-only checklist built from unit state."""
    done = sum(1 for u in units if u.status is Status.DONE)
    lines = [
        f"# {cr} progress",
        "",
        "Generated by `ralph status --write` from `units/*.json`. Don't edit it by hand:",
        "use `ralph unblock`, `ralph set` or `ralph add-unit` to change a unit.",
        "",
        f"**{done}/{len(units)} units done.**",
        "",
    ]
    for unit in units:
        tags = " ".join(t for t in (unit.priority, unit.size) if t)
        line = f"- [{SYMBOLS[unit.status]}] {unit.id} {unit.title}"
        if tags:
            line += f" ({tags})"
        if unit.triage:
            line += " — triage: accept with `ralph set " + unit.id + " --status todo`"
        if unit.status is Status.BLOCKED and unit.blocker:
            line += f" — blocked: {unit.blocker}"
        lines.append(line)
    return "\n".join(lines) + "\n"
