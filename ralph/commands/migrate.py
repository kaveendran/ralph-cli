"""`ralph migrate` — move a change request from the old loop to the harness.

Reads what the old loop left behind and writes the harness's files:
- units/*.json from the plan, with each unit's status from the old progress
  checklist (units that only appear in the checklist are kept too);
- units/<ID>.notes.md from the per-unit detail blocks (`### U033 — …`);
- prompts/instructions.md from build.md, without the parts that told the
  agent to commit, edit the progress file or pick units (the harness does
  those now); every removed line is listed so you can review it;
- .ralph/config.toml with gates found in scripts/test-*.sh, if missing;
- .gitignore entries for the harness's runtime files.
The old progress file and build.md are left as they are, so the old loop
(`ralph legacy start`) still works. `--dry-run` shows all of this without
writing anything. Run it on a branch.
"""

import re
from datetime import date
from pathlib import Path

from ralph import ui
from ralph.commands.common import load_project
from ralph.errors import RalphError
from ralph.fsutil import read_text, write_text_atomic
from ralph.graph.compile import compile_plan
from ralph.model.plan import parse_plan
from ralph.model.progress import parse_legacy_progress
from ralph.model.store import UnitStore
from ralph.model.unit import Status, Unit
from ralph.paths import CrPaths, ProjectPaths, normalise_cr
from ralph.prompts import render_template
from ralph.runner import compat

DROP_SECTIONS = re.compile(r"progress tracking|commit cadence|completion gate", re.IGNORECASE)
DROP_LINES = re.compile(
    r"\bgit (add|commit|push|tag)\b|\b(update|mark|edit|maintain|keep)\b[^.\n]{0,60}\bprogress (file|tracker)"
    r"|\[!\]\s*blocked|pick the (highest|next)|re-read the (spec|plan)|fix every failure"
    r"|unrelated pre-existing|loop runner|push is handled", re.IGNORECASE)
GITIGNORE_LINES = ("log/", ".ralph/run.lock", ".ralph/control/")
GATE_SCRIPTS = {"unit": "test-unit.sh", "api": "test-api.sh", "e2e": "test-e2e.sh", "paid": "test-paid.sh"}


def register(subparsers) -> None:
    p = subparsers.add_parser("migrate", help="move a change request from the old loop to the harness")
    p.add_argument("--cr", required=True, help="change request to migrate, e.g. 2 or cr2")
    p.add_argument("--dry-run", action="store_true", help="show what would change; write nothing")
    p.add_argument("--force", action="store_true", help="migrate even if the CR already has units")
    p.set_defaults(handler=run)


def _blocks(lines: list[str]) -> list[list[str]]:
    """Group a blockquote's lines together, so it's kept or removed whole."""
    blocks: list[list[str]] = []
    for line in lines:
        quoted = line.startswith(">")
        if quoted and blocks and blocks[-1][0].startswith(">"):
            blocks[-1].append(line)
        else:
            blocks.append([line])
    return blocks


def convert_build_prompt(text: str, cr_name: str) -> tuple[str, list[str]]:
    """(instructions.md text, the lines that were removed)."""
    removed, kept, dropping = [], [], False
    for block in _blocks(text.splitlines()):
        line = block[0]
        if line.startswith("## "):
            dropping = bool(DROP_SECTIONS.search(line))
            if dropping:
                removed.append(f"[section] {line[3:].strip()}")
                continue
        if line.startswith("# ") and not kept:
            continue    # the old title; replaced below
        if dropping:
            continue
        if any(DROP_LINES.search(part) for part in block):
            removed.append(" ".join(part.lstrip("> ").strip() for part in block)[:160]
                           + (" [blockquote]" if len(block) > 1 else ""))
            continue
        kept.extend(block)
    header = (f"# {cr_name} instructions (migrated from build.md)\n\n"
              "> Generated by `ralph migrate`. Lines that told the agent to commit, edit the progress file or "
              "pick units were removed, because the harness does those now. Review the rest.\n")
    return header + "\n".join(kept).strip() + "\n", removed


def detect_gates(root: Path) -> dict[str, str]:
    return {name: f"bash scripts/{script}" for name, script in GATE_SCRIPTS.items()
            if (root / "scripts" / script).exists()}


def render_config(gates: dict[str, str], claude_version: str = "") -> str:
    regular = {k: v for k, v in gates.items() if k != "paid"}
    by_type = {"default": [g for g in ("unit",) if g in regular]}
    if "api" in regular:
        for unit_type in ("api", "service", "migration", "core"):
            by_type[unit_type] = [g for g in ("unit", "api") if g in regular]
    if "e2e" in regular:
        by_type["frontend"] = [g for g in ("unit", "e2e") if g in regular]
    gate_lines = "\n".join(f'{name} = "{cmd}"' for name, cmd in gates.items()) or '# unit = "bash scripts/test-unit.sh"'
    type_lines = "\n".join(f"{t} = {names!r}".replace("'", '"') for t, names in by_type.items() if names) \
        or '# default = ["unit"]'
    paid = '["paid"]' if "paid" in gates else "[]"
    return render_template("config.toml", GATES=gate_lines, BY_TYPE=type_lines, PAID_GATES=paid,
                           CLAUDE_VERSION=claude_version or "2.1.311")


def plan_migration(project: ProjectPaths, cr: CrPaths) -> dict:
    if not cr.plan.exists():
        raise RalphError(f"{cr.name} has no plan at {cr.plan}; migrate needs it.")
    plan = parse_plan(cr.plan)
    legacy = parse_legacy_progress(cr.legacy_progress)
    compiled = compile_plan(plan, {}, cr.name)
    units = compiled.units

    for unit in units.values():
        entry = legacy.entries.get(unit.id)
        if entry:
            unit.status = entry.status
            if entry.status is Status.BLOCKED:
                # "Title — blocked on X" → "blocked on X"
                reason = entry.text.split(" — ", 1)[1] if " — " in entry.text else entry.text
                unit.blocker = reason.strip() or "blocked in the old progress file"
    order = max((u.order for u in units.values()), default=0)
    for unit_id, entry in legacy.entries.items():
        if unit_id not in units:
            order += 1
            units[unit_id] = Unit(
                id=unit_id, title=re.sub(r"\*+", "", entry.text).strip()[:80] or unit_id, cr=cr.name,
                status=entry.status, order=order,
                description=f"Migrated from the progress file; the plan has no entry for {unit_id}.\n\n{entry.text}")

    instructions, removed = ("", [])
    if cr.legacy_build_prompt.exists():
        instructions, removed = convert_build_prompt(cr.legacy_build_prompt.read_text(encoding="utf-8"), cr.name)
    gitignore = read_text(project.root / ".gitignore")
    return {
        "units": units, "issues": compiled.issues, "notes": legacy.details,
        "instructions": instructions, "removed": removed,
        "config": None if project.config.exists() else render_config(detect_gates(project.root),
                                                                     _version_or_blank()),
        "gitignore_add": [line for line in GITIGNORE_LINES if line not in gitignore.split()],
    }


def _version_or_blank() -> str:
    try:
        compat.find_claude()
        return compat.installed_version()
    except RalphError:
        return ""


def run(args) -> int:
    project, _ = load_project()
    cr = project.cr(normalise_cr(args.cr))
    store = UnitStore(cr.units_dir)
    if store.exists() and not args.force:
        raise RalphError(f"{cr.name} already has units in {cr.units_dir}.", "Pass --force to migrate it again.")
    plan = plan_migration(project, cr)
    units: dict[str, Unit] = plan["units"]

    counts = {s.value: sum(1 for u in units.values() if u.status is s) for s in Status}
    ui.header(f"migrate — {cr.name}", "dry run: nothing is written" if args.dry_run else "writing the harness files")
    ui.info(f"  Units: {len(units)} ({', '.join(f'{v} {k}' for k, v in counts.items() if v)})")
    ui.info(f"  Unit notes from the progress file's detail blocks: {len(plan['notes'])}")
    for issue in plan["issues"]:
        ui.warn(f"{issue.unit_id}: {issue.reason}")
    if plan["removed"]:
        ui.info(f"  From build.md, {len(plan['removed'])} line(s) removed for instructions.md:")
        for line in plan["removed"]:
            ui.info(f"    - {line[:120]}")
    if plan["config"]:
        ui.info(f"  .ralph/config.toml with gates: {', '.join(detect_gates(project.root)) or 'none found'}")
    if plan["gitignore_add"]:
        ui.info(f"  .gitignore += {', '.join(plan['gitignore_add'])}")
    if args.dry_run:
        return 0

    for unit in units.values():
        if unit.status is Status.DONE:
            unit.done = {"by": "migrated", "at": date.today().isoformat()}
    store.save_all(units.values())
    for unit_id, block in plan["notes"].items():
        if unit_id in units:
            write_text_atomic(store.notes_path(unit_id), f"## Migrated from the progress file\n\n{block}")
    if plan["instructions"]:
        write_text_atomic(cr.instructions, plan["instructions"])
    if plan["config"]:
        write_text_atomic(project.config, plan["config"])
    if plan["gitignore_add"]:
        gitignore_path = project.root / ".gitignore"
        existing = read_text(gitignore_path).rstrip("\n")
        addition = "\n".join(["", "# ralph harness runtime files", *plan["gitignore_add"]])
        write_text_atomic(gitignore_path, (existing + "\n" if existing else "") + addition.lstrip("\n") + "\n")
    ui.ok(f"Wrote {len(units)} units to {cr.units_dir}. Review the changes with 'git status', then commit them.")
    ui.info(f"  Next: ralph start --cr {cr.name} --dry-run")
    return 0
